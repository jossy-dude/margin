#!/usr/bin/env python3
"""Write the Plain look's widget layout from the hand one: same views, the Plain look's one grotesque."""
import pathlib
res = pathlib.Path(__file__).resolve().parent.parent / 'modules/margin-native/android/src/main/res/layout'
s = (res / 'mg_widget_card.xml').read_text()
for a in ('@font/mg_marker', '@font/mg_type', '@font/mg_serif'):
    s = s.replace(a, '@font/mg_grotesk')
s = s.replace('<!-- v0.7.6: the widget', '<!-- GENERATED by tools/widget-layouts.py from mg_widget_card.xml; do not edit.\n     v0.7.6: the widget', 1)
(res / 'mg_widget_card_plain.xml').write_text(s)
