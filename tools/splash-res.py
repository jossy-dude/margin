#!/usr/bin/env python3
"""v0.7.7 splash resources (SPEC §6): one splash per skin, a vector M, no PNG.

Writes, under android/app/src/main/res:
  drawable/ic_splash_{pen,day}[_light|_dark].xml and drawable-night/ic_splash_{pen,day}.xml
  values/splash_colors.xml, values-night/splash_colors.xml
  values-v31/splash_styles.xml   (Theme.Splash.<Skin>[.Light|.Dark])

Run from the repo root: python3 tools/splash-res.py
"""
import pathlib

R = pathlib.Path('android/app/src/main/res')

# Splash paper per skin, light and dark: the skin's own paper (src/tokens/theme.ts), Daylight a mid sky colour.
SKINS = {
    'Collage': ('#F3EFE7', '#1E2125'),
    'Refined': ('#FAF4E6', '#3C352C'),
    'Original': ('#FAF5EB', '#10141A'),
    'Plain': ('#F4F3F0', '#17181A'),
    'Daylight': ('#DCE8F5', '#141B2E'),
}
# The M's ink and its tape: the brand pen for the paper skins, Daylight's noon accent for Daylight.
INKS = {'pen': ('#8A4B27', '#E3AA82', '#F3E3A8', '#4A3F22'), 'day': ('#2563A8', '#8FA9E8', '#F6E3B8', '#2A3550')}


def vector(m, tape):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- v0.7.7 splash: the M and its tape, no card and no PNG, on a 288 dp canvas whose middle 192 dp circle is what
     Android 12+ shows. A vector, so it is sharp at whatever size One UI draws the splash icon. Generated by
     tools/splash-res.py; edit that, not this. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="288dp" android:height="288dp"
    android:viewportWidth="288" android:viewportHeight="288">
  <group android:pivotX="144" android:pivotY="145" android:scaleX="1.3" android:scaleY="1.3">
  <path android:fillColor="{tape}" android:pathData="M90,140 L198,134 L199,156 L148,159 C140,159 132,163 124,164 L92,166 Z"/>
  <path android:strokeColor="{m}" android:strokeWidth="11" android:strokeLineCap="round" android:strokeLineJoin="round"
      android:fillColor="#00000000" android:pathData="M100,186 L100,104 L144,163 L188,104 L188,186"/>
  <path android:strokeColor="{m}" android:strokeWidth="1.6" android:strokeLineCap="round" android:fillColor="#00000000"
      android:pathData="M84,106 L84,184"/>
  </group>
</vector>
'''


def colors(night):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- v0.7.7: one splash paper per skin (tools/splash-res.py). The *_light/*_dark pairs are for a forced mode. -->',
           '<resources>']
    for k, (light, dark) in SKINS.items():
        lk = k.lower()
        if not night:
            out.append(f'  <color name="splash_{lk}_light">{light}</color>')
            out.append(f'  <color name="splash_{lk}_dark">{dark}</color>')
        out.append(f'  <color name="splash_{lk}">{dark if night else light}</color>')
    out.append('</resources>\n')
    return '\n'.join(out)


def styles():
    st = ['<?xml version="1.0" encoding="utf-8"?>',
          '<!-- v0.7.7: the splash wears the last skin. MainActivity picks one of these for the NEXT launch with',
          '     SplashScreen.setSplashScreenTheme (Android 13+); "auto" follows the phone, Light/Dark are for a forced mode.',
          '     Generated by tools/splash-res.py. -->', '<resources>']
    for k in SKINS:
        lk, ink = k.lower(), 'day' if k == 'Daylight' else 'pen'
        for suf, col, ic in (('', f'splash_{lk}', f'ic_splash_{ink}'),
                             ('.Light', f'splash_{lk}_light', f'ic_splash_{ink}_light'),
                             ('.Dark', f'splash_{lk}_dark', f'ic_splash_{ink}_dark')):
            st += [f'  <style name="Theme.Splash.{k}{suf}" parent="AppTheme">',
                   f'    <item name="android:windowBackground">@color/{col}</item>',
                   f'    <item name="android:windowSplashScreenBackground">@color/{col}</item>',
                   f'    <item name="android:windowSplashScreenAnimatedIcon">@drawable/{ic}</item>',
                   '  </style>']
    st.append('</resources>\n')
    return '\n'.join(st)


def main():
    (R / 'drawable-night').mkdir(exist_ok=True)
    (R / 'values-v31').mkdir(exist_ok=True)
    for name, (ml, md, tl, td) in INKS.items():
        (R / f'drawable/ic_splash_{name}_light.xml').write_text(vector(ml, tl))
        (R / f'drawable/ic_splash_{name}_dark.xml').write_text(vector(md, td))
        (R / f'drawable/ic_splash_{name}.xml').write_text(vector(ml, tl))
        (R / f'drawable-night/ic_splash_{name}.xml').write_text(vector(md, td))
    (R / 'values/splash_colors.xml').write_text(colors(False))
    (R / 'values-night/splash_colors.xml').write_text(colors(True))
    (R / 'values-v31/splash_styles.xml').write_text(styles())


if __name__ == '__main__':
    main()
