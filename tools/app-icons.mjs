// v0.7.8.13 (owner's ask 4): Marrow's app icons, one per look, from one drawing: the splash's M and its tape on a
// 108 dp adaptive canvas (safe zone 66 dp), with a monochrome layer for Android 13's themed icons.
//   node tools/app-icons.mjs  → android/app/src/main/res/drawable/ic_marrow_{fg,bg}_<v>.xml
//                               android/app/src/main/res/mipmap-anydpi-v26/ic_marrow_<v>.xml
//                               android/app/src/main/res/mipmap-xxxhdpi/ic_marrow_<v>.png (pre-8.0 fallback)
//                               assets/icons/<v>.png (Settings' picker)
import { chromium } from 'playwright';
import { mkdirSync, writeFileSync } from 'node:fs';

const RES = 'android/app/src/main/res', APP = 'assets/icons';
for (const d of ['drawable', 'mipmap-anydpi-v26', 'mipmap-xxxhdpi']) mkdirSync(`${RES}/${d}`, { recursive: true });
mkdirSync(APP, { recursive: true });

/* The M from the splash (tools/splash-res.py), on its 288 canvas, centred at (144, 145). */
const TAPE = 'M90,140 L198,134 L199,156 L148,159 C140,159 132,163 124,164 L92,166 Z';
const M = 'M100,186 L100,104 L144,163 L188,104 L188,186';
const RULE = 'M84,106 L84,184';
/* 288 → 108, the M about 46 dp wide: inside the 48 dp keyline that every launcher mask keeps whole. */
const S = 0.4, TX = 54 - 144, TY = 54 - 145;

export const ICONS = {
  paper: { name: 'Paper', bg: ['#FAF4E6'], ink: '#8A4B27', tape: '#F3E3A8' },
  denim: { name: 'Denim', bg: ['#2F5A86'], ink: '#FAF4E6', tape: '#E9B949' },
  ink: { name: 'Ink', bg: ['#17181A'], ink: '#ECEBE7', tape: '#4F7FB8' },
  sky: { name: 'Sky', bg: ['#F6C77A', '#7FB2E0'], ink: '#2B3038', tape: '#FFFFFF' },
};

const group = (body) => `  <group android:pivotX="144" android:pivotY="145" android:scaleX="${S}" android:scaleY="${S}" android:translateX="${TX}" android:translateY="${TY}">\n${body}  </group>\n`;
const fg = (v) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/app-icons.mjs; edit that, not this. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
${group(`    <path android:fillColor="${v.tape}" android:pathData="${TAPE}"/>
    <path android:strokeColor="${v.ink}" android:strokeWidth="13" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" android:pathData="${M}"/>
    <path android:strokeColor="${v.ink}" android:strokeWidth="2.2" android:strokeLineCap="round" android:fillColor="#00000000" android:pathData="${RULE}"/>
`)}</vector>
`;
const mono = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/app-icons.mjs: the themed-icon layer (Android 13), the M alone. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
${group(`    <path android:strokeColor="#FF000000" android:strokeWidth="13" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" android:pathData="${M}"/>
`)}</vector>
`;
const bg = (v) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/app-icons.mjs; edit that, not this. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
${v.bg.length === 1 ? `  <path android:fillColor="${v.bg[0]}" android:pathData="M0,0h108v108h-108z"/>` : `  <path android:pathData="M0,0h108v108h-108z">
    <aapt:attr name="android:fillColor">
      <gradient android:type="linear" android:startX="54" android:startY="0" android:endX="54" android:endY="108" android:startColor="${v.bg[0]}" android:endColor="${v.bg[1]}"/>
    </aapt:attr>
  </path>`}
</vector>
`;
const adaptive = (k) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/app-icons.mjs. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_marrow_bg_${k}"/>
    <foreground android:drawable="@drawable/ic_marrow_fg_${k}"/>
    <monochrome android:drawable="@drawable/ic_marrow_mono"/>
</adaptive-icon>
`;
writeFileSync(`${RES}/drawable/ic_marrow_mono.xml`, mono);
for (const [k, v] of Object.entries(ICONS)) {
  writeFileSync(`${RES}/drawable/ic_marrow_fg_${k}.xml`, fg(v));
  writeFileSync(`${RES}/drawable/ic_marrow_bg_${k}.xml`, bg(v));
  writeFileSync(`${RES}/mipmap-anydpi-v26/ic_marrow_${k}.xml`, adaptive(k));
}

/* The same drawing as SVG, for the PNGs: the full 108 canvas, clipped to a circle like most launchers show it. */
const svg = (v, px) => `<svg xmlns="http://www.w3.org/2000/svg" width="${px}" height="${px}" viewBox="18 18 72 72">
  <defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${v.bg[0]}"/><stop offset="1" stop-color="${v.bg[1] ?? v.bg[0]}"/></linearGradient><clipPath id="c"><circle cx="54" cy="54" r="36"/></clipPath></defs>
  <g clip-path="url(#c)"><rect x="0" y="0" width="108" height="108" fill="url(#g)"/>
  <g transform="translate(54 54) scale(${S}) translate(-144 -145)">
    <path d="${TAPE}" fill="${v.tape}"/>
    <path d="${M}" fill="none" stroke="${v.ink}" stroke-width="13" stroke-linecap="round" stroke-linejoin="round"/>
    <path d="${RULE}" fill="none" stroke="${v.ink}" stroke-width="2.2" stroke-linecap="round"/>
  </g></g></svg>`;
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 192, height: 192 }, deviceScaleFactor: 1 });
for (const [k, v] of Object.entries(ICONS)) {
  await p.setContent(`<html><body style="margin:0;background:transparent">${svg(v, 192)}</body></html>`);
  const png = await p.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: 192, height: 192 } });
  writeFileSync(`${RES}/mipmap-xxxhdpi/ic_marrow_${k}.png`, png);
  writeFileSync(`${APP}/${k}.png`, png);
  console.log(k);
}
await b.close();
