/**
 * v0.7.7.8 (SPEC §5, D3): Daylight's widget surface is a static three-stop gradient of the current sky keyframe,
 * fully opaque. Each stop is the sky's own stop with the app's pane laid over it at that sky's pane alpha, so the
 * widget reads like a pane in the app and its inks hold the same contrast.
 *
 * This test is also the generator: `WRITE_WIDGET_SKY=1 npx jest widget-sky` writes the 12 drawables.
 * Without it, the checked-in drawables must match what the sky table and PANE_ALPHA make.
 */
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { join } from 'path';
import { DAY_INK, NOW, PANE_ALPHA } from '../tokens/skins/daylight';

type Scheme = 'light' | 'dark';
const SKIES = JSON.parse(readFileSync(join(__dirname, '..', '..', 'assets', 'sky', 'skies.json'), 'utf8')) as Record<Scheme, Record<string, { stops: [string, string, string] }>>;
const RES = join(__dirname, '..', '..', 'modules', 'margin-native', 'android', 'src', 'main', 'res', 'drawable');
const PANE: Record<Scheme, string> = { light: '#FFFFFF', dark: '#10141B' };

const rgb = (h: string) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const hex = (c: number[]) => `#${c.map((v) => Math.round(v).toString(16).padStart(2, '0')).join('').toUpperCase()}`;
const over = (base: string, top: string, a: number) => { const b = rgb(base), t = rgb(top); return hex(b.map((v, i) => v * (1 - a) + t[i]! * a)); };
const lum = (h: string) => { const [r, g, b] = rgb(h).map((v) => { const s = v / 255; return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4; }); return 0.2126 * r! + 0.7152 * g! + 0.0722 * b!; };
const ratio = (a: string, b: string) => { const x = lum(a), y = lum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };

const stopsFor = (scheme: Scheme, key: string) => SKIES[scheme][key]!.stops.map((s) => over(s, PANE[scheme], PANE_ALPHA[scheme][key as keyof (typeof PANE_ALPHA)['light']]));
const xml = (scheme: Scheme, key: string) => {
  const [a, b, c] = stopsFor(scheme, key);
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by src/test/widget-sky.test.ts (WRITE_WIDGET_SKY=1); do not edit. v0.7.7.8: Daylight's widget surface for
     the ${scheme} ${key} sky: the sky's three stops under the app's pane at alpha ${PANE_ALPHA[scheme][key as 'noon']}. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
  <gradient android:angle="270" android:startColor="${a}" android:centerColor="${b}" android:endColor="${c}"/>
</shape>
`;
};

const ALL = (['light', 'dark'] as const).flatMap((scheme) => Object.keys(SKIES[scheme]).map((key) => [scheme, key] as const));

describe('Daylight widget skies', () => {
  if (process.env.WRITE_WIDGET_SKY) for (const [s, k] of ALL) writeFileSync(join(RES, `mg_sky_${s}_${k}.xml`), xml(s, k));

  it('has the six keyframes in both modes', () => { expect(ALL).toHaveLength(12); });
  it.each(ALL)('mg_sky_%s_%s.xml matches the sky table and the pane alpha', (s, k) => {
    const f = join(RES, `mg_sky_${s}_${k}.xml`);
    expect(existsSync(f)).toBe(true);
    expect(readFileSync(f, 'utf8')).toBe(xml(s, k));
  });
  /* The bar only repeats the countdown next to it, so it isn't the sole carrier of anything (WCAG 1.4.11 doesn't bind);
     the light amber is the app's own `now` and stays readable, the dark one clears 3:1. */
  it.each(ALL)('%s %s: ink, ink2 and ink3 hold 4.5:1 on every stop; the now bar stays visible', (s, k) => {
    for (const stop of stopsFor(s, k)) {
      for (const ink of [DAY_INK[s].ink, DAY_INK[s].ink2, DAY_INK[s].ink3]) expect(ratio(ink, stop)).toBeGreaterThanOrEqual(4.5);
      expect(ratio(NOW[s], stop)).toBeGreaterThanOrEqual(s === 'dark' ? 3 : 1.5);
    }
  });
});
